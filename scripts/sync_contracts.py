#!/usr/bin/env python3
"""Generate the shared contracts into each client (ADR 0004 section 5, ADR 0008).

- Validates `design-tokens/base.json` (W3C Design Tokens format): every token has a
  white and a dark value in `$extensions.modes`, references (`{path}`) exist and do not
  loop, values match their `$type`, fonts are bundled, and every background declared
  with `$extensions.pair` reaches WCAG AA contrast with its foreground in both themes.
- Copies `backend/schema.graphql` into each client present.
- Web: `web/src/generated/tokens.css` (white in `:root`, dark under
  `prefers-color-scheme: dark`) and `tokens.ts` (the union of token names and `token()`).
- Android: `Tokens.kt` (a `Tokens` class with one typed property per token and the
  `whiteTokens` and `darkTokens` instances) and the schema in `app/src/main/graphql/`.
- iOS: `Tokens.swift` in the `UI` target (a `Tokens` struct with one typed property per
  token and the `Tokens.white` and `Tokens.dark` instances) and the schema in `graphql/`.

Usage (from anywhere):

    python3 scripts/sync_contracts.py           validate and write the generated files
    python3 scripts/sync_contracts.py --check   fail if a generated file is out of date
"""

from __future__ import annotations

import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
TOKENS = Path("design-tokens/base.json")
SCHEMA = Path("backend/schema.graphql")
WEB_GENERATED = Path("web/src/generated")
ANDROID_PACKAGE = "com.sebastianartaza.fulbito.ui.theme.generated"
ANDROID_TOKENS = Path("android/app/src/main/java", *ANDROID_PACKAGE.split("."), "Tokens.kt")
ANDROID_SCHEMA = Path("android/app/src/main/graphql/schema.graphql")
KOTLIN_TYPES = {
    "color": "Color",
    "dimension": "Dp",
    "fontWeight": "FontWeight",
    "fontFamily": "String",
}
IOS_TOKENS = Path("ios/Packages/UI/Theme/Generated/Tokens.swift")
IOS_SCHEMA = Path("ios/graphql/schema.graphql")
SWIFT_TYPES = {
    "color": "Color",
    "dimension": "CGFloat",
    "fontWeight": "Font.Weight",
    "fontFamily": "String",
}
SWIFT_WEIGHTS = {
    100: "ultraLight",
    200: "thin",
    300: "light",
    400: "regular",
    500: "medium",
    600: "semibold",
    700: "bold",
    800: "heavy",
    900: "black",
}
THEMES = ("white", "dark")
BUNDLED_FONTS = ("Inter",)
MINIMUM_CONTRAST = 4.5
CHECK_FLAG = "--check"
HEADER = "Generated by scripts/sync_contracts.py from design-tokens/base.json. Do not edit."
# "{color.neutral.0}" -> "color.neutral.0"; "#FFFFFF" -> no match
REFERENCE = re.compile(r"^\{([^{}]+)\}$")
# "#1B1F1C" -> match; "#1B1F1C80" -> match; "green" -> no match
HEX_COLOR = re.compile(r"^#[0-9A-Fa-f]{6}(?:[0-9A-Fa-f]{2})?$")
# "8px" -> match; "0.5px" -> match; "eight" -> no match
DIMENSION = re.compile(r"^\d+(?:\.\d+)?px$")
# "nav.item.on-surface" -> ["nav", "item", "on", "surface"]
NAME_PARTS = re.compile(r"[.\-]")


@dataclass(frozen=True)
class Token:
    """One token of the tree.

    Attributes:
        path: dotted path, e.g. `nav.item.label.color`.
        type: its `$type`.
        modes: raw value per theme (a literal or a `{reference}`).
        pair: for a background, the path of its foreground.
    """

    path: str
    type: str
    modes: dict[str, Any]
    pair: str | None


def flatten(node: dict[str, Any], prefix: str = "") -> dict[str, Token]:
    """Every token of a group, by dotted path.

    Args:
        node: a group of the tree (keys starting with `$` are metadata).
        prefix: the group's own path.

    Returns:
        Tokens by path.
    """
    tokens: dict[str, Token] = {}
    for key, child in node.items():
        if key.startswith("$") or not isinstance(child, dict):
            continue
        path = f"{prefix}.{key}" if prefix else key
        if "$type" in child:
            extensions = child.get("$extensions", {})
            tokens[path] = Token(
                path=path,
                type=child["$type"],
                modes=dict(extensions.get("modes", {})),
                pair=extensions.get("pair"),
            )
        else:
            tokens.update(flatten(child, path))
    return tokens


def type_problem(token: Token, value: Any, theme: str) -> str | None:
    """Why a resolved value does not fit its token's type, if it does not.

    Args:
        token: the token.
        value: its resolved value in one theme.
        theme: the theme.

    Returns:
        The problem, or None when the value fits.
    """
    where = f"{token.path} ({theme})"
    if token.type == "color":
        valid = isinstance(value, str) and HEX_COLOR.match(value) is not None
        return None if valid else f"{where}: {value!r} is not a #RRGGBB colour"
    if token.type == "dimension":
        valid = isinstance(value, str) and DIMENSION.match(value) is not None
        return None if valid else f"{where}: {value!r} is not a dimension in px"
    if token.type == "fontWeight":
        valid = isinstance(value, int) and 100 <= value <= 900
        return None if valid else f"{where}: {value!r} is not a font weight (100 to 900)"
    if token.type == "fontFamily":
        if value in BUNDLED_FONTS:
            return None
        return f"{where}: {value!r} is not a bundled font family ({', '.join(BUNDLED_FONTS)})"
    return f"{token.path}: unknown $type {token.type!r}"


class Resolver:
    """Resolves references per theme, collecting every problem once."""

    def __init__(self, tokens: dict[str, Token]) -> None:
        self.tokens = tokens
        self.problems: list[str] = []
        self._done: dict[tuple[str, str], Any] = {}

    def report(self, problem: str) -> None:
        """Record a problem unless it was already recorded.

        Args:
            problem: the message.
        """
        if problem not in self.problems:
            self.problems.append(problem)

    def value(self, path: str, theme: str, chain: tuple[str, ...] = ()) -> Any:
        """The literal value of a token in a theme.

        A problem is reported where it starts (the token without a value, the unknown
        reference, the cycle); tokens that depend on it fail silently.

        Args:
            path: the token.
            theme: `white` or `dark`.
            chain: the references followed to get here.

        Returns:
            The value, or None when it cannot be resolved.
        """
        key = (path, theme)
        if key in self._done:
            return self._done[key]
        if path in chain:
            self.report(f"{path}: reference cycle {' -> '.join((*chain, path))}")
            return None
        token = self.tokens[path]
        if theme not in token.modes:
            self.report(f"{path}: no {theme} value")
            result = None
        else:
            raw = token.modes[theme]
            reference = REFERENCE.match(raw) if isinstance(raw, str) else None
            if reference is None:
                result = raw
            elif reference.group(1) not in self.tokens:
                self.report(f"{path} ({theme}): references unknown token {reference.group(1)}")
                result = None
            else:
                result = self.value(reference.group(1), theme, (*chain, path))
        if result is not None and (problem := type_problem(token, result, theme)):
            self.report(problem)
            result = None
        self._done[key] = result
        return result


def luminance(hex_color: str) -> float:
    """Relative luminance of a colour (WCAG 2.x).

    Args:
        hex_color: `#RRGGBB`.

    Returns:
        A value from 0 (black) to 1 (white).
    """
    channels = [int(hex_color[index : index + 2], 16) / 255 for index in (1, 3, 5)]
    linear = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def contrast(first: str, second: str) -> float:
    """Contrast ratio between two colours (WCAG 2.x).

    Args:
        first: `#RRGGBB`.
        second: `#RRGGBB`.

    Returns:
        From 1 to 21.
    """
    light, dark = sorted((luminance(first), luminance(second)), reverse=True)
    return (light + 0.05) / (dark + 0.05)


def validate(tree: dict[str, Any]) -> tuple[dict[str, dict[str, Any]], list[str]]:
    """Resolve every token in both themes and check types and contrast pairs.

    Args:
        tree: the parsed `base.json`.

    Returns:
        `({theme: {path: value}}, problems)`; the values are only usable without problems.
    """
    tokens = flatten(tree)
    resolver = Resolver(tokens)
    resolved = {
        theme: {path: resolver.value(path, theme) for path in sorted(tokens)} for theme in THEMES
    }
    for token in tokens.values():
        if token.pair is None:
            continue
        if token.pair not in tokens:
            resolver.report(f"{token.path}: pair {token.pair} is not a token")
            continue
        for theme in THEMES:
            background, foreground = resolved[theme][token.path], resolved[theme][token.pair]
            if not isinstance(background, str) or not isinstance(foreground, str):
                continue
            ratio = contrast(background[:7], foreground[:7])
            if ratio < MINIMUM_CONTRAST:
                resolver.report(
                    f"{token.path} and {token.pair} in {theme}: contrast {ratio:.2f}:1, "
                    f"below {MINIMUM_CONTRAST}:1 (WCAG AA)"
                )
    return resolved, resolver.problems


def css_name(path: str) -> str:
    """The CSS custom property of a token.

    Args:
        path: `nav.item.label.color`.

    Returns:
        `--nav-item-label-color`.
    """
    return "--" + path.replace(".", "-")


def render_css(resolved: dict[str, dict[str, Any]]) -> str:
    """The web tokens as CSS custom properties.

    Args:
        resolved: values per theme and path.

    Returns:
        White values in `:root`, dark ones under `prefers-color-scheme: dark`.
    """
    white = [f"  {css_name(path)}: {value};" for path, value in resolved["white"].items()]
    dark = [f"    {css_name(path)}: {value};" for path, value in resolved["dark"].items()]
    return "\n".join(
        [
            f"/* {HEADER} */",
            ":root {",
            "  color-scheme: light dark;",
            *white,
            "}",
            "",
            "@media (prefers-color-scheme: dark) {",
            "  :root {",
            *dark,
            "  }",
            "}",
            "",
        ]
    )


def render_typescript(paths: list[str]) -> str:
    """The typed accessor of the web tokens.

    Args:
        paths: every token path, sorted.

    Returns:
        A module with `TokenName` and `token(name)`, which returns the CSS `var()`.
    """
    names = [f'  | "{path}"' for path in paths]
    return "\n".join(
        [
            f"// {HEADER}",
            "",
            "export type TokenName =",
            *names[:-1],
            names[-1] + ";",
            "",
            "export function token(name: TokenName): string {",
            '  return `var(--${name.replaceAll(".", "-")})`;',
            "}",
            "",
        ]
    )


def kotlin_name(path: str) -> str:
    """The Kotlin property of a token.

    Args:
        path: `nav.item.on-surface`.

    Returns:
        `navItemOnSurface`.
    """
    first, *rest = NAME_PARTS.split(path)
    return first + "".join(part[:1].upper() + part[1:] for part in rest)


def kotlin_value(token_type: str, value: Any) -> str:
    """A resolved value as a Kotlin expression.

    Args:
        token_type: the token's `$type`.
        value: its resolved value.

    Returns:
        `Color(0xFF1B1F1C)`, `8.dp`, `FontWeight(600)` or `"Inter"`.
    """
    if token_type == "color":
        alpha = value[7:9] or "FF"
        return f"Color(0x{alpha.upper()}{value[1:7].upper()})"
    if token_type == "dimension":
        return f"{value.removesuffix('px')}.dp"
    if token_type == "fontWeight":
        return f"FontWeight({value})"
    return json.dumps(value)


def render_kotlin(resolved: dict[str, dict[str, Any]], types: dict[str, str]) -> str:
    """The Android tokens as a Compose `Tokens` class and its two instances.

    Args:
        resolved: values per theme and path.
        types: the `$type` of each path.

    Returns:
        A Kotlin file with `Tokens`, `whiteTokens` and `darkTokens`.
    """
    fields = [
        f"    val {kotlin_name(path)}: {KOTLIN_TYPES[types[path]]}," for path in resolved["white"]
    ]
    instances: list[str] = []
    for theme in THEMES:
        instances += ["", f"val {theme}Tokens = Tokens("]
        instances += [
            f"    {kotlin_name(path)} = {kotlin_value(types[path], value)},"
            for path, value in resolved[theme].items()
        ]
        instances.append(")")
    return "\n".join(
        [
            f"// {HEADER}",
            "",
            f"package {ANDROID_PACKAGE}",
            "",
            "import androidx.compose.ui.graphics.Color",
            "import androidx.compose.ui.text.font.FontWeight",
            "import androidx.compose.ui.unit.Dp",
            "import androidx.compose.ui.unit.dp",
            "",
            "/** Every design token, typed; one instance per bundled theme. */",
            "data class Tokens(",
            *fields,
            ")",
            *instances,
            "",
        ]
    )


def swift_value(token_type: str, value: Any) -> str:
    """A resolved value as a Swift expression.

    Args:
        token_type: the token's `$type`.
        value: its resolved value.

    Returns:
        `Color(argb: 0xFF1B1F1C)`, `8`, `.semibold` or `"Inter"`.
    """
    if token_type == "color":
        alpha = value[7:9] or "FF"
        return f"Color(argb: 0x{alpha.upper()}{value[1:7].upper()})"
    if token_type == "dimension":
        return value.removesuffix("px")
    if token_type == "fontWeight":
        return f".{SWIFT_WEIGHTS[int(value)]}"
    return json.dumps(value)


def render_swift(resolved: dict[str, dict[str, Any]], types: dict[str, str]) -> str:
    """The iOS tokens as a SwiftUI `Tokens` struct and its two instances.

    Args:
        resolved: values per theme and path.
        types: the `$type` of each path.

    Returns:
        A Swift file with `Tokens`, `Tokens.white` and `Tokens.dark`.
    """
    fields = [
        f"    public let {kotlin_name(path)}: {SWIFT_TYPES[types[path]]}"
        for path in resolved["white"]
    ]
    instances: list[str] = []
    for theme in THEMES:
        instances += [f"    static let {theme} = Tokens("]
        instances += [
            f"        {kotlin_name(path)}: {swift_value(types[path], value)},"
            for path, value in resolved[theme].items()
        ]
        instances.append("    )")
    return "\n".join(
        [
            f"// {HEADER}",
            "",
            "import SwiftUI",
            "",
            "/// Every design token, typed; one instance per bundled theme.",
            "public struct Tokens: Sendable {",
            *fields,
            "}",
            "",
            "public extension Tokens {",
            *instances,
            "}",
            "",
            "private extension Color {",
            "    init(argb: UInt32) {",
            "        self.init(",
            "            .sRGB,",
            "            red: Double((argb >> 16) & 0xFF) / 255,",
            "            green: Double((argb >> 8) & 0xFF) / 255,",
            "            blue: Double(argb & 0xFF) / 255,",
            "            opacity: Double((argb >> 24) & 0xFF) / 255",
            "        )",
            "    }",
            "}",
            "",
        ]
    )


def outputs(
    root: Path, resolved: dict[str, dict[str, Any]], types: dict[str, str]
) -> dict[Path, bytes]:
    """Every generated file of every client present, with its content.

    Args:
        root: the workspace.
        resolved: the token values per theme.
        types: the `$type` of each token.

    Returns:
        Content by path relative to the workspace.
    """
    files: dict[Path, bytes] = {}
    if (root / "web").is_dir():
        files[WEB_GENERATED / "tokens.css"] = render_css(resolved).encode()
        files[WEB_GENERATED / "tokens.ts"] = render_typescript(list(resolved["white"])).encode()
        files[WEB_GENERATED / "schema.graphql"] = (root / SCHEMA).read_bytes()
    if (root / "android").is_dir():
        files[ANDROID_TOKENS] = render_kotlin(resolved, types).encode()
        files[ANDROID_SCHEMA] = (root / SCHEMA).read_bytes()
    if (root / "ios").is_dir():
        files[IOS_TOKENS] = render_swift(resolved, types).encode()
        files[IOS_SCHEMA] = (root / SCHEMA).read_bytes()
    return files


def run(root: Path, check: bool) -> int:
    """Validate, then write or check the generated files.

    Args:
        root: the workspace.
        check: compare with the files on disk instead of writing them.

    Returns:
        Process exit code.
    """
    problems: list[str] = []
    if not (root / SCHEMA).is_file():
        problems.append(f"{SCHEMA} not found: export the schema first")
    try:
        tree = json.loads((root / TOKENS).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        problems.append(f"{TOKENS} cannot be read: {error}")
        tree = None
    resolved: dict[str, dict[str, Any]] = {}
    types: dict[str, str] = {}
    if tree is not None:
        types = {path: token.type for path, token in flatten(tree).items()}
        resolved, token_problems = validate(tree)
        problems.extend(token_problems)
    if problems:
        for problem in problems:
            print(f"{TOKENS}: {problem}", file=sys.stderr)
        return 1
    files = outputs(root, resolved, types)
    if check:
        stale = [
            path
            for path, content in files.items()
            if not (root / path).is_file() or (root / path).read_bytes() != content
        ]
        for path in stale:
            print(f"{path} is out of date: run python3 scripts/sync_contracts.py", file=sys.stderr)
        return 1 if stale else 0
    for path, content in files.items():
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.is_file() or target.read_bytes() != content:
            target.write_bytes(content)
    print(f"Contracts generated: {len(files)} files.")
    return 0


def main(argv: list[str]) -> int:
    """Run the script.

    Args:
        argv: command-line arguments (`--check` or nothing).

    Returns:
        Process exit code.
    """
    if any(arg != CHECK_FLAG for arg in argv):
        print(__doc__)
        return 2
    return run(ROOT, CHECK_FLAG in argv)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
