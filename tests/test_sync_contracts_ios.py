"""Tests of requirement 0006, AC-1: `scripts/sync_contracts.py` generates the iOS files.

When `ios/` exists, the script writes the SwiftUI tokens (one `Tokens` struct with a
typed property per token and the `white` and `dark` instances) into the `UI` target and
copies the backend schema into `ios/graphql/`, and `--check` covers them. The token tree
and the workspace come from `tests/test_sync_contracts.py`.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest
from test_sync_contracts import SCHEMA, output, sync
from test_sync_contracts import workspace as base_workspace

__all__ = ["base_workspace"]

TOKENS = Path("ios/Packages/UI/Theme/Generated/Tokens.swift")
IOS_SCHEMA = Path("ios/graphql/schema.graphql")


@pytest.fixture
def workspace(base_workspace: Path) -> Path:
    """The workspace of the web tests, with an iOS client too."""
    (base_workspace / "ios").mkdir()
    return base_workspace


def instance(source: str, name: str) -> str:
    """The arguments of the `static let <name> = Tokens(...)` instance in the source."""
    match = re.search(rf"static let {name} = Tokens\((.*?)\n\s*\)", source, re.DOTALL)
    assert match, f"{name} not found"
    return match.group(1)


def test_ac1_generates_swiftui_tokens_with_typed_names(workspace: Path) -> None:
    """AC-1: one typed public property per token, named in camelCase, with a header."""
    assert sync(workspace).returncode == 0
    source = (workspace / TOKENS).read_text()
    assert source.startswith("// Generated by scripts/sync_contracts.py")
    assert "import SwiftUI" in source
    assert "public struct Tokens: Sendable {" in source
    assert "public let navItemLabelColor: Color" in source
    assert "public let colorNeutral0: Color" in source
    assert "public let onSurface: Color" in source
    assert "public let navItemGap: CGFloat" in source
    assert "public let navItemWeight: Font.Weight" in source
    assert "public let navItemFont: String" in source


def test_ac1_white_and_dark_values_with_references_resolved(workspace: Path) -> None:
    """AC-1: each instance carries its theme's values; references are resolved."""
    assert sync(workspace).returncode == 0
    source = (workspace / TOKENS).read_text()
    white, dark = instance(source, "white"), instance(source, "dark")
    assert "surface: Color(argb: 0xFFFFFFFF)," in white
    assert "surface: Color(argb: 0xFF121614)," in dark
    assert "navItemLabelColor: Color(argb: 0xFF1B1F1C)," in white
    assert "navItemLabelColor: Color(argb: 0xFFE8EDE9)," in dark
    assert "navItemGap: 8," in white
    assert "navItemWeight: .semibold," in dark
    assert 'navItemFont: "Inter"' in white


def test_ac1_schema_is_copied_byte_for_byte(workspace: Path) -> None:
    """AC-1: the backend schema lands unchanged in the iOS project."""
    assert sync(workspace).returncode == 0
    assert (workspace / IOS_SCHEMA).read_bytes() == SCHEMA.encode()


def test_ac1_check_covers_the_ios_files(workspace: Path) -> None:
    """AC-1: `--check` fails when a generated iOS file was edited, passes after a run."""
    assert sync(workspace).returncode == 0
    assert sync(workspace, "--check").returncode == 0
    tokens = workspace / TOKENS
    tokens.write_text(tokens.read_text().replace("0xFF121614", "0xFF000000"))
    edited = sync(workspace, "--check")
    assert edited.returncode == 1
    assert "Tokens.swift" in output(edited)
    assert sync(workspace).returncode == 0
    assert sync(workspace, "--check").returncode == 0


def test_ac1_web_files_are_still_generated(workspace: Path) -> None:
    """AC-1: with both clients present, both get their files."""
    assert sync(workspace).returncode == 0
    assert (workspace / "web/src/generated/tokens.css").is_file()
    assert (workspace / TOKENS).is_file()


def test_ac1_without_ios_no_ios_files(base_workspace: Path) -> None:
    """AC-1: the iOS files appear only when `ios/` exists."""
    assert sync(base_workspace).returncode == 0
    assert not (base_workspace / TOKENS).exists()
    assert not (base_workspace / IOS_SCHEMA).exists()
