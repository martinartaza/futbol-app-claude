"""Tests of requirement 0005, AC-1: `scripts/sync_contracts.py` generates the Android files.

When `android/` exists, the script writes the Compose tokens (one `Tokens` class with a
typed property per token, a `whiteTokens` and a `darkTokens` instance) and copies the
backend schema into the app, and `--check` covers them. The token tree and the
workspace come from `tests/test_sync_contracts.py`.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest
from test_sync_contracts import SCHEMA, output, sync
from test_sync_contracts import workspace as base_workspace

__all__ = ["base_workspace"]

TOKENS = Path("android/app/src/main/java/com/sebastianartaza/fulbito/ui/theme/generated/Tokens.kt")
ANDROID_SCHEMA = Path("android/app/src/main/graphql/schema.graphql")


@pytest.fixture
def workspace(base_workspace: Path) -> Path:
    """The workspace of the web tests, with an Android client too."""
    (base_workspace / "android").mkdir()
    return base_workspace


def instance(source: str, name: str) -> str:
    """The body of the `val <name> = Tokens(...)` instance in the generated source."""
    match = re.search(rf"val {name} = Tokens\((.*?)\n\)", source, re.DOTALL)
    assert match, f"{name} not found"
    return match.group(1)


def test_ac1_generates_compose_tokens_with_typed_names(workspace: Path) -> None:
    """AC-1: one typed property per token, named in camelCase, with a header."""
    assert sync(workspace).returncode == 0
    source = (workspace / TOKENS).read_text()
    assert source.startswith("// Generated by scripts/sync_contracts.py")
    assert "package com.sebastianartaza.fulbito.ui.theme.generated" in source
    assert "data class Tokens(" in source
    assert "val navItemLabelColor: Color," in source
    assert "val colorNeutral0: Color," in source
    assert "val onSurface: Color," in source
    assert "val navItemGap: Dp," in source
    assert "val navItemWeight: FontWeight," in source
    assert "val navItemFont: String," in source


def test_ac1_white_and_dark_values_with_references_resolved(workspace: Path) -> None:
    """AC-1: each instance carries its theme's values; references are resolved."""
    assert sync(workspace).returncode == 0
    source = (workspace / TOKENS).read_text()
    white, dark = instance(source, "whiteTokens"), instance(source, "darkTokens")
    assert "surface = Color(0xFFFFFFFF)," in white
    assert "surface = Color(0xFF121614)," in dark
    assert "navItemLabelColor = Color(0xFF1B1F1C)," in white
    assert "navItemLabelColor = Color(0xFFE8EDE9)," in dark
    assert "navItemGap = 8.dp," in white
    assert "navItemWeight = FontWeight(600)," in dark
    assert 'navItemFont = "Inter",' in white


def test_ac1_schema_is_copied_byte_for_byte(workspace: Path) -> None:
    """AC-1: the backend schema lands unchanged in the Android app."""
    assert sync(workspace).returncode == 0
    assert (workspace / ANDROID_SCHEMA).read_bytes() == SCHEMA.encode()


def test_ac1_check_covers_the_android_files(workspace: Path) -> None:
    """AC-1: `--check` fails when a generated Android file was edited, passes after a run."""
    assert sync(workspace).returncode == 0
    assert sync(workspace, "--check").returncode == 0
    tokens = workspace / TOKENS
    tokens.write_text(tokens.read_text().replace("0xFF121614", "0xFF000000"))
    edited = sync(workspace, "--check")
    assert edited.returncode == 1
    assert "Tokens.kt" in output(edited)
    assert sync(workspace).returncode == 0
    assert sync(workspace, "--check").returncode == 0


def test_ac1_web_files_are_still_generated(workspace: Path) -> None:
    """AC-1: with both clients present, both get their files."""
    assert sync(workspace).returncode == 0
    assert (workspace / "web/src/generated/tokens.css").is_file()
    assert (workspace / TOKENS).is_file()


def test_ac1_without_android_no_android_files(base_workspace: Path) -> None:
    """AC-1: the Android files appear only when `android/` exists."""
    assert sync(base_workspace).returncode == 0
    assert not (base_workspace / TOKENS).exists()
    assert not (base_workspace / ANDROID_SCHEMA).exists()
